export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, bn };

export function isLocale(v: unknown): v is Locale {
  return v === "en" || v === "bn";
}

/** Translate with {placeholders}. Falls back to English, then the key. */
export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  const s = MESSAGES[locale][key] ?? MESSAGES.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : s;
}

export function tFor(locale: Locale) {
  return (key: MessageKey, vars?: Record<string, string | number>) => t(locale, key, vars);
}

/** Localised path: bn pages live under /bn (real URLs for hreflang); en is unprefixed. */
export function localizePath(path: string, locale: Locale): string {
  const clean = path.replace(/^\/(en|bn)(?=\/|$)/, "") || "/";
  return locale === "bn" ? `/bn${clean === "/" ? "" : clean}` || "/bn" : clean;
}
